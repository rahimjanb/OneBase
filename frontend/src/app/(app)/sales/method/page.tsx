import { Section } from "@/components/sales/bits";
import { SalesFrame } from "@/components/sales/SalesFrame";
import type { SalesSearchParams } from "@/lib/sales/query";

export const metadata = { title: "Как считается · Продажи" };

function Rules({ items }: { items: React.ReactNode[] }) {
  return (
    <ul className="list-disc space-y-1.5 pl-5 text-sm leading-relaxed text-ink-2 marker:text-ink-3">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  );
}

const sources: [string, string, string][] = [
  ["Заказы", "orders/, orders_count/", "факт, АКБ, календари, ассортимент, магазины"],
  ["Возвраты", "order_returns/", "вычитаются по строкам документа"],
  ["Визиты", "visits/, visits_count/", "страйк, визиты без заказа, календарь визитов"],
  ["Сотрудники", "users/", "ТП, должности (доставщики не ТП)"],
  ["Торговые точки", "markets/", "названия, регион точки"],
  ["Товары и типы", "products/, product_types/", "категории отчёта"],
  ["Склады и остатки", "stocks/, product_balances/", "вкладка «Остатки»"],
  ["Перемещения", "stock_transfers/", "вкладка «Первичка»"],
  ["Платежи, прайс-листы, поставщики, валюты, договоры", "payments/, price_lists/, price_list_items/, providers/, currencies/, contracts/", "загружаются для сверки, в отчётах пока не используются"],
  ["Планы агентов", "API планов Linko (staff_balance)", "вкладка «Планы», план ТП"],
];

export default async function MethodPage({ searchParams }: { searchParams: Promise<SalesSearchParams> }) {
  const sp = await searchParams;
  return (
    <SalesFrame title="Как считается" subtitle="Правила расчёта вторички, первички и остатков — и что в данных Linko устроено иначе, чем кажется" crumbs={[{ label: "Как считается" }]} sp={sp}>
      <Section title="Факт продаж (вторичка)">
        <Rules
          items={[
            <><b className="text-ink">Факт = заказы − возвраты.</b> Заказ входит, только если статус «delivered», дата приёмки магазином (accepted_time) попадает в месяц и не позже отчётного дня, а филиал — не «Завод».</>,
            <><b className="text-ink">Дата продажи — приёмка (accepted_time), а не плановая доставка.</b> Плановую доставку назначают и на воскресенье, а принимают в понедельник. accepted_time Linko отдаёт по местному времени (Ташкент): у заказов, не менявшихся после приёмки, он ровно на 5 часов больше времени изменения в UTC.</>,
            <><b className="text-ink">Возвраты</b> — статус «delivered», дата создания возврата в месяце (другой даты у возврата нет), филиал не «Завод». Вес и сумма берутся по строкам документа: у части возвратов вес в шапке нулевой, а товар лежит в строках. Возврат уменьшает кг и сумму того региона и агента, где он оформлен.</>,
            <><b className="text-ink">Филиал «Завод»</b> — экспорт и крупный опт, не регион: во вторичку не входит и показывается отдельной плиткой «Экспорт и опт».</>,
            <><b className="text-ink">АКБ</b> — число уникальных торговых точек (по ID точки), у которых за месяц был хотя бы один включённый заказ. Возвраты АКБ не уменьшают: покупку точка всё-таки сделала.</>,
            <><b className="text-ink">Категория</b> — по типу товара: Бамбук, Кекс, Трубочки, Печенье, Шоколад, Песочный, Придзел (в Linko — «Снек», Twizos) и Помадка (все фасовки одной категорией). Типы вне этого списка (импорт, бонус, оборудование) в итог входят, но в карточки категорий — нет; они видны в блоке «Качество данных».</>,
          ]}
        />
      </Section>

      <Section title="Визиты и страйк">
        <Rules
          items={[
            <>Визиты загружаются из Linko API (visits/). Визит «с заказом» — есть заказ того же агента в той же точке <b className="text-ink">в день ввода заказа</b> (created_date): приёмка обычно на сутки позже визита, и по дате приёмки визит почти никогда не совпал бы с заказом.</>,
            <>Страйк (конверсия) = визиты с заказом ÷ выполненные визиты. «Визиты без заказа» — выполненные визиты, после которых в тот же день в этой точке заказа не было (это не «точки, которые не купили»).</>,
            <>Доставщики, курьеры и экспедиторы — не ТП: их «визиты» — это доставки, в конверсию и «Проблемных агентов» они не входят.</>,
            <>Агент оценивается при 20 и более визитах за месяц; сравнение — с медианой своего региона.</>,
          ]}
        />
      </Section>

      <Section title="Первичка и остатки">
        <Rules
          items={[
            <><b className="text-ink">Первичка</b> — перемещения Linko со склада завода на склады регионов в статусах «отдано» или «принято». Дата — выдача, без неё — приёмка. Плана первички в Linko нет.</>,
            <><b className="text-ink">Остатки Linko — в штуках.</b> Кг = штуки × вес штуки; вес штуки = Σ веса ÷ Σ количества по строкам заказов за год (в справочнике товаров веса нет). Коробки = кг ÷ вес коробки из названия, и только если в коробке целое число штук. Умножать штуки на вес коробки нельзя — это завысит остаток во столько раз, сколько штук в коробке.</>,
            <>Склад региона — склад с тем же названием, что у региона. Остальные склады («эски», «интеграция», «Основной»…) в остаток регионов не складываются и показаны отдельно. Остаток завода в итог страны не входит.</>,
            <>Дефицит — хватит меньше чем на 15 дней продаж, затоварка — больше чем на 30, «не продаётся» — остаток есть, а продаж за 90 дней нет.</>,
          ]}
        />
      </Section>

      <Section title="Источники данных" hint="браузер к Linko не обращается — только сервер OneBase">
        <div className="-mx-4 overflow-x-auto px-4 sm:-mx-5 sm:px-5">
          <table className="w-full min-w-max text-sm">
            <thead>
              <tr className="border-b border-line text-left text-[11px] uppercase tracking-wide text-ink-3">
                <th className="py-2 pr-4">Данные</th>
                <th className="py-2 pr-4">Linko External API</th>
                <th className="py-2">Где используются</th>
              </tr>
            </thead>
            <tbody>
              {sources.map(([what, endpoint, where]) => (
                <tr key={what} className="border-b border-line last:border-0">
                  <td className="py-2 pr-4 text-ink">{what}</td>
                  <td className="py-2 pr-4 font-mono text-xs text-ink-2">{endpoint}</td>
                  <td className="py-2 text-ink-2">{where}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Section>

      <Section title="Что показала сверка с API" hint="расхождения с прежним описанием интеграции">
        <Rules
          items={[
            <><b className="text-ink">Визиты в API есть</b> (visits/, visits_count/), выгрузка из интерфейса для них не нужна.</>,
            <><b className="text-ink">Ссылка «возврат → заказ» есть</b>: у строк возврата заполнены order_id и order_product_id. Правило при этом не менялось — возврат вычитается по своей дате.</>,
            <>Лимит страницы возвратов сейчас 1000, как и у остальных ресурсов (не 500). OneBase запрашивает возвраты по 500 и сам замечает, если сервер отдаёт страницу меньше запрошенной.</>,
            <>Остаток (balance) приходит строкой «0.000000000» — разбирается как число.</>,
            <>Фильтр is_synced на сервере сейчас ни на что не влияет: заказы отдаются все.</>,
          ]}
        />
      </Section>

      <Section title="Чего в Linko нет">
        <Rules
          items={[
            <>Плана РОП по регионам и категориям и плана «Завод» — они загружаются в OneBase файлом («Настройки → Продажи: оргструктура и планы»). План ТП приходит из API планов Linko.</>,
            <>Разбивки экспорта по странам, плана первички, премий и ФОТ, цен «вход дилеру» — в External API этих данных нет.</>,
            <>Даты реализации у возврата и веса штуки в справочнике товаров — нет; вес штуки считается из заказов.</>,
            <>Запись в Linko (sync_*, отметки «синхронизировано») OneBase не выполняет: отметка скрывает документы из выдачи для других интеграций, например 1С.</>,
          ]}
        />
      </Section>
    </SalesFrame>
  );
}
