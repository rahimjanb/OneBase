    [Fact]
    public void Columns_go_canonical_first_then_ordinal()
    {
        Assert.Equal(["Twizos", "Бамбук", "Кекс 1 кг", "Кекс 2.5 кг", "Печенье", "Помадка 1 кг", "Помадка 230 гр", "Помадка 420 Гр", "Трубочка", "Фрулли", "Шоколад"],
            KpiMath.Order(["Шоколад", "Фрулли", "Twizos", "Трубочка", "Кекс 2.5 кг", "Кекс 1 кг", "Помадка 420 Гр", "Помадка 230 гр", "Помадка 1 кг", "Печенье", "Бамбук"]));
        Assert.Equal(["Тотал", "Могуль", "Twizos", "АКБ", "Бамбук + Шоколад", "Кекс", "Трубочка + Печенье"],
            KpiMath.Order(["Кекс", "АКБ", "Трубочка + Печенье", "Twizos", "Бамбук + Шоколад", "Могуль", "Тотал"]));
        Assert.True(KpiMath.IsSupervisorIndicator("Октябрь Могуль Вес 9,5 млн Супер"));
        Assert.Equal(["кг", "сум", "шт", "АКБ"], new[] { "product_sales_weight", "sales_sum", "product_sales_amount", "active_client_count" }.Select(KpiMath.UnitOf));
    }

    /// <summary>Выполнение до тысячных к чётному (как Linko): 121/400 → 0,302, 42/160 → 0,262, 89/80 → 1,112.</summary>
    [Fact]
    public void Execution_rounds_half_to_even()
    {
        Assert.Equal(0.302m, KpiMath.Pct(121, 400));
        Assert.Equal(0.262m, KpiMath.Pct(42, 160));
        Assert.Equal(1.112m, KpiMath.Pct(89, 80));
        Assert.Equal(0m, KpiMath.Pct(5, 0));
    }

    /// <summary>
    /// Порог и «Бонус 100%» — первый уровень с бонусом; премия — бонус × выполнение, не выше 100%, ниже порога 0. Рахмонов (Наманган, Могуль):
    /// 1 770 000 × 37 828 790 / 47 270 537 = 1 416 462,82 (как начислил Linko на 15.10).
    /// </summary>
    [Fact]
    public void Premium_follows_linko_levels()
    {
        var levels = KpiMath.ParseLevels("""[{"from":0,"to":80,"bonus":0,"type":"percent_from_bonus_amount_for_all"},{"from":80,"to":1000,"bonus":1770000,"type":"percent_from_bonus_amount_for_all"}]""");
        Assert.Equal((0.8m, 1_770_000m), KpiMath.BonusLevel(levels));
        Assert.Equal(1_416_462.82m, Math.Round(KpiMath.Premium(levels, 37_828_790m / 47_270_537m), 2));
        Assert.Equal(0m, KpiMath.Premium(levels, 0.7914m));
        Assert.Equal(1_770_000m, KpiMath.Premium(levels, 1.2404m));
        Assert.Equal(1_770_000m, KpiMath.Premium(levels, 12m)); // выше последнего уровня — последний

        var fixedBonus = KpiMath.ParseLevels("""[{"from":0,"to":60,"bonus":0,"type":"percent_from_sales"},{"from":60,"to":70,"bonus":350000,"type":"bonus"},{"from":70,"to":100,"bonus":500000,"type":"bonus"}]""");
        Assert.Equal((0.6m, 350_000m), KpiMath.BonusLevel(fixedBonus));
        Assert.Equal(350_000m, KpiMath.Premium(fixedBonus, 0.65m));
        Assert.Equal(500_000m, KpiMath.Premium(fixedBonus, 0.95m));
        Assert.Equal((null, 0m), KpiMath.BonusLevel(KpiMath.ParseLevels("[]")));
        Assert.Empty(KpiMath.ParseLevels("не json"));

        Assert.Equal("ok", KpiMath.Tone(1, 0.8m));
        Assert.Equal("warn", KpiMath.Tone(0.8m, 0.8m));
        Assert.Equal("bad", KpiMath.Tone(0.97m, null));
    }

    /// <summary>Доля месяца для прогноза: 20 из 31 дня — 0,645; от 0,98 месяц считается полным.</summary>
    [Fact]
    public void Forecast_share_of_the_month()
    {
        Assert.Equal(20m / 31, KpiMath.MonthShare(20, 31));
        Assert.Equal(1m, KpiMath.MonthShare(31, 31));
        Assert.Equal(1m, KpiMath.MonthShare(0, 31));
    }
